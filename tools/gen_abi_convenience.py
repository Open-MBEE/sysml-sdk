"""Generate abi/src/generated_convenience.rs: one extern "C" function per convenience member.

Input: convenience.json (tools/extract_convenience.py). Every member, whatever its contexts, gets one
function `sysmlv2_conv_<member in snake_case>` that checks the element's metaclass is one of the
member's contexts (NOT_APPLICABLE otherwise), converts the arguments, and calls the member's body in
abi/src/convenience.rs: the family members a generic body per variant with the kind's metaclass or
library type, the others a body of their own, named after the member.

C types (tools/naming.py, `convenience_abi`): a Scope or VisibilityFilter is a uint32_t (the literal's
index), a Boolean a bool, a String a Str, an element a Handle. Results: an element list Handles, one
element Ref, a Boolean Bool, an Integer or UnlimitedNatural Int (`*` is INT64_MAX), a Real Real, a list of
strings Str (JSON), a literal Str (tagged JSON), a name-keyed map Str (JSON pairs of a name and a handle, as
a decimal string). A digest over the functions' signatures is embedded, so a language core can refuse a
library generated from a different contract.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

from naming import ROOT, convenience_abi, convenience_digest, convenience_symbol, spelling

OUT = ROOT / "abi" / "src" / "generated_convenience.rs"
# The crate items the generated functions may use; the `use` line names those they do.
CRATE_ITEMS = ["read", "read_str", "Bool", "Handle", "Handles", "Int", "Real", "Ref", "Session", "Status", "Str"]
USES = object()

RUST_PARAM = {"enum": "u32", "Boolean": "bool", "String": "*const Str", "element": "Handle"}
OUT_TYPE = {"H": "Handles", "R": "Ref", "B": "Bool", "I": "Int", "F": "Real", "T": "Str", "L": "Str", "M": "Str"}
PUT = {"H": "put_handles", "R": "put_reference", "B": "put_flag", "I": "put_integer", "F": "put_real",
       "T": "put_text", "L": "put_text", "M": "put_text"}

# The generic body of each family variant, and what it takes from the record.
FAMILY_BODY = {
    ("kindLists", "list"): ("kind_list", "scope, visibility, library", "kindMetaclass"),
    ("kindLists", "exact"): ("kind_exact", "scope, visibility, library", "returns"),
    ("kindLists", "semantic"): ("kind_semantic", "scope, visibility, library", "libraryType"),
    ("kindLists", "semanticTest"): ("semantic_test", "", "libraryType"),
    ("kindLists", "byName"): ("kind_by_name", "&name, scope, visibility, library", "kindMetaclass"),
    ("memberLists", "list"): ("member_list", "scope, visibility, library", "kindMetaclass"),
    ("memberLists", "byName"): ("member_by_name", "&name, scope, visibility, library", "kindMetaclass"),
    ("definitionLists", "list"): ("def_list", "scope", "kindMetaclass"),
    ("definitionLists", "exact"): ("def_exact", "scope", "returns"),
    ("definitionLists", "semantic"): ("def_semantic", "scope", "libraryType"),
    ("definitionLists", "byName"): ("def_by_name", "&name, scope", "kindMetaclass"),
    ("definitionLists", "nameMap"): ("def_name_map", "scope", "kindMetaclass"),
}


def main() -> None:
    table = json.loads((ROOT / "convenience.json").read_text(encoding="utf-8"))
    by_name: dict[str, list[dict]] = {}
    for m in table["members"]:
        by_name.setdefault(m["name"], []).append(m)
    digest = convenience_digest(table)
    out = [
        "//! Generated by tools/gen_abi_convenience.py from convenience.json. Do not edit.",
        f"//! Convenience signature digest: {digest}",
        "",
        "#![allow(unused_variables, clippy::not_unsafe_ptr_arg_deref)]",
        "",
        "use crate::convenience::{self as c};",
        USES,
        "",
        f'pub const CONVENIENCE_DIGEST: &str = "{digest}";',
        "",
        "/// SHA-256 hex of the convenience members' signatures this library was generated with. Static.",
        "#[no_mangle]",
        "pub extern \"C\" fn sysmlv2_convenience_digest() -> *const u8 {",
        "    CONVENIENCE_DIGEST.as_ptr()",
        "}",
        "",
        "#[no_mangle]",
        "pub extern \"C\" fn sysmlv2_convenience_digest_len() -> usize {",
        "    CONVENIENCE_DIGEST.len()",
        "}",
        "",
    ]
    for name in sorted(by_name):
        recs = by_name[name]
        m = recs[0]
        params, code = convenience_abi(m)
        contexts = ", ".join(f'"{r["on"]}"' for r in recs)
        sig = ["s: *mut Session", "h: Handle"]
        sig += [f"{ident(p['name'])}: {RUST_PARAM[kind]}" for p, kind in zip(m["params"], params)]
        sig.append(f"out: *mut {OUT_TYPE[code]}")
        pointers = ["s.is_null()", "out.is_null()"]
        pointers += [f"{ident(p['name'])}.is_null()" for p, kind in zip(m["params"], params) if kind == "String"]
        out.append(f"/// `{name}` on {', '.join(r['on'] for r in recs)}.")
        out.append("#[no_mangle]")
        out.append(f"pub unsafe extern \"C\" fn {convenience_symbol(name)}({', '.join(sig)}) -> Status {{")
        out.append(f"    if {' || '.join(pointers)} {{ return Status::InvalidArg; }}")
        out.append("    let s = &mut *s;")
        out.append("    let e = match s.elem(h) { Ok(e) => e, Err(st) => return st };")
        out.append(f'    if let Err(st) = c::applicable(s, e, "{name}", &[{contexts}]) {{ return st; }}')
        args = []
        for p, kind in zip(m["params"], params):
            n = ident(p["name"])
            if kind == "enum":
                conv = "scope" if p["type"]["type"] == "Scope" else "visibility"
                out.append(f"    let {n} = match c::{conv}(s, {n}) {{ Ok(x) => x, Err(st) => return st }};")
            elif kind == "String":
                out.append(f'    let {n} = match read_str(&*{n}) {{ Ok(x) => x, Err(st) => return s.fail(st, "{name}: {n} is not UTF-8") }};')
            elif kind == "element":
                out.append(f"    let {n} = match s.elem({n}) {{ Ok(x) => x, Err(st) => return st }};")
            args.append(n)
        call = body_call(m, args)
        out.append(f"    let result = {call};")
        out.append(f'    let answer = c::answer(s, "{name}", result);')
        out.append(f'    read::{PUT[code]}(s, "{name}", answer, &mut *out)')
        out.append("}")
        out.append("")
    # Import only the crate items the functions use (no Real while no member answers one).
    body = "\n".join(line for line in out if line is not USES)
    used = [n for n in CRATE_ITEMS if re.search(rf"\b{n}\b", body)]
    out = [f"use crate::{{{', '.join(used)}}};" if line is USES else line for line in out]
    OUT.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(by_name)} functions, digest {digest[:12]}")


# Rust's keywords, which a parameter's name is escaped from as a raw identifier (`r#type`).
RUST_KEYWORDS = {"as", "async", "await", "break", "const", "continue", "crate", "dyn", "else", "enum", "extern",
                 "false", "fn", "for", "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub",
                 "ref", "return", "self", "static", "struct", "super", "trait", "true", "type", "unsafe", "use",
                 "where", "while", "abstract", "become", "box", "do", "final", "macro", "override", "priv",
                 "try", "typeof", "unsized", "virtual", "yield"}


def ident(name: str) -> str:
    """A parameter's name as a Rust identifier."""
    return f"r#{name}" if name in RUST_KEYWORDS else name


def body_call(m: dict, args: list[str]) -> str:
    if m["family"]:
        fn, shape, key = FAMILY_BODY[(m["family"], m["variant"])]
        const = m["returns"]["type"] if key == "returns" else m[key]
        rest = shape.replace("&name", "&name")
        parts = ["s", "e"] + ([rest] if rest else []) + [f'"{const}"']
        return f"c::{fn}({', '.join(parts)})"
    passed = ["s", "e"] + [f"&{a}" if p["type"]["kind"] == "primitive" and p["type"]["type"] == "String" else a
                           for a, p in zip(args, m["params"])]
    return f"c::{spelling(m['name'], 'cpp')}({', '.join(passed)})"


if __name__ == "__main__":
    main()
