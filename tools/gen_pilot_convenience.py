"""Generate java/src/<package>/pilot/ConvenienceMembers.java: the Pilot engine's dispatch of the
protocol's `find` request to the convenience members' bodies.

Input: convenience.json (tools/extract_convenience.py). Every member name gets one case that checks
the element's metaclass is one of the member's contexts (`notApplicable` otherwise), takes the
arguments by parameter name (the table's default where the request leaves one out), and calls the
member's body in pilot/Convenience.java: the family members a generic body per variant with the kind's
metaclass or library type, the others a body of their own, named after the member. An UnlimitedNatural
result goes out as the protocol has it (`*` for unbounded).
"""

from __future__ import annotations

import json

from naming import JAVA_SRC, ROOT, convenience_runtime

OUT = JAVA_SRC / "pilot" / "ConvenienceMembers.java"

# The generic body of each family variant, its arguments after the element, and what it takes from
# the record (the same bodies as the binding library's, tools/gen_abi_convenience.py).
FAMILY_BODY = {
    ("kindLists", "list"): ("kindList", "scope, visibility, library", "kindMetaclass"),
    ("kindLists", "exact"): ("kindExact", "scope, visibility, library", "returns"),
    ("kindLists", "semantic"): ("kindSemantic", "scope, visibility, library", "libraryType"),
    ("kindLists", "semanticTest"): ("semanticTest", "", "libraryType"),
    ("kindLists", "byName"): ("kindByName", "name, scope, visibility, library", "kindMetaclass"),
    ("memberLists", "list"): ("memberList", "scope, visibility, library", "kindMetaclass"),
    ("memberLists", "byName"): ("memberByName", "name, scope, visibility, library", "kindMetaclass"),
    ("definitionLists", "list"): ("defList", "scope", "kindMetaclass"),
    ("definitionLists", "exact"): ("defExact", "scope", "returns"),
    ("definitionLists", "semantic"): ("defSemantic", "scope", "libraryType"),
    ("definitionLists", "byName"): ("defByName", "name, scope", "kindMetaclass"),
    ("definitionLists", "nameMap"): ("defNameMap", "scope", "kindMetaclass"),
}


def argument(p: dict, kind: str) -> str:
    """The Java expression that takes parameter `p` from the request's arguments `a`."""
    n, default = p["name"], p["default"]
    if kind == "scope":
        return f'Convenience.scope(a, "{n}", "{default}")'
    if kind == "visibility":
        return f'Convenience.visibility(a, "{n}", "{default}")'
    if kind == "bool":
        return f'Convenience.bool(a, "{n}", {"true" if default else "false"})'
    if kind == "str":
        if default is not None:
            raise SystemExit(f"{p['name']}: a String parameter with a default has no conversion yet")
        return f'Convenience.str(a, "{n}")'
    if kind == "element":
        return f'c.element(a, "{n}")'
    raise SystemExit(f"{n}: no conversion for parameter kind {kind}")


def body_call(m: dict, args: dict[str, str]) -> str:
    if m["family"]:
        fn, shape, key = FAMILY_BODY[(m["family"], m["variant"])]
        const = m["returns"]["type"] if key == "returns" else m[key]
        parts = ["e"] + [args[n.strip()] for n in shape.split(",") if n.strip()] + [f'"{const}"']
        return f"c.{fn}({', '.join(parts)})"
    return f"c.{m['name']}({', '.join(['e'] + [args[p['name']] for p in m['params']])})"


def main() -> None:
    table = json.loads((ROOT / "convenience.json").read_text(encoding="utf-8"))
    by_name: dict[str, list[dict]] = {}
    for m in table["members"]:
        by_name.setdefault(m["name"], []).append(m)
    out = [
        "// Generated by tools/gen_pilot_convenience.py from convenience.json. Do not edit.",
        "package org.openmbee.sysml.pilot;",
        "",
        "import java.util.Map;",
        "",
        "/**",
        " * The convenience members of {@code convenience.json} by name: each checks the element's metaclass",
        " * against the member's contexts, takes the arguments by parameter name (the default where the",
        " * request leaves one out) and calls the member's body in {@link Convenience}.",
        " */",
        "final class ConvenienceMembers {",
        "    private ConvenienceMembers() { }",
        "",
        "    /** The number of convenience members this dispatch answers. */",
        f"    static final int COUNT = {len(by_name)};",
        "",
        "    static Object find(Convenience c, Object e, String member, Map<?, ?> a) throws ReflectiveOperationException {",
        "        switch (member) {",
    ]
    for name in sorted(by_name):
        recs = by_name[name]
        m = recs[0]
        params, result = convenience_runtime(m)
        contexts = ", ".join(f'"{r["on"]}"' for r in recs)
        args = {p["name"]: argument(p, kind) for p, (_, kind, _) in zip(m["params"], params)}
        call = body_call(m, args)
        if result == "unlimited":
            call = f"Convenience.unlimited({call})"
        out.append(f'            case "{name}":')
        out.append(f"                c.applicable(e, member, {contexts});")
        out.append(f"                return {call};")
    out += [
        "            default:",
        '                throw new PilotException("badRequest", "no convenience member " + member);',
        "        }",
        "    }",
        "}",
        "",
    ]
    OUT.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(by_name)} members")


if __name__ == "__main__":
    main()
